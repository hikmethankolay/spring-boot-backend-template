-- Personal access tokens (token/): long-lived API keys a user creates for scripts and integrations. Each one acts as
-- its user with that user's current role (capped by app.access-tokens.max-role) and a READ or WRITE scope.

CREATE TABLE access_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Deleting the user deletes their tokens.
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name         VARCHAR(100) NOT NULL,
    -- SHA-256 of the token given to the user once; the token itself is never stored.
    token_hash   VARCHAR(64)  NOT NULL,
    scope        VARCHAR(10)  NOT NULL,
    expires_at   TIMESTAMPTZ  NOT NULL,
    -- Updated at most once a minute, so a busy script does not write on every request.
    last_used_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_access_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_access_tokens_scope CHECK (scope IN ('READ', 'WRITE')),
    CONSTRAINT ck_access_tokens_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_access_tokens_user_id ON access_tokens (user_id);
CREATE INDEX ix_access_tokens_expires_at ON access_tokens (expires_at);
