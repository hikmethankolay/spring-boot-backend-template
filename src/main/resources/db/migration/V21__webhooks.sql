-- Outbound webhooks (webhook/): users register HTTPS endpoints that receive signed POSTs (Standard Webhooks) when
-- events happen. Deliveries are an outbox: written in the transaction of the change, sent and retried afterwards.

CREATE TABLE webhook_endpoints (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Deleting the user deletes their endpoints and, through them, the deliveries.
    user_id                BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    url                    VARCHAR(2048) NOT NULL,
    description            VARCHAR(200),
    event_types            TEXT[]        NOT NULL,
    -- Signing secrets (whsec_...), AES-GCM encrypted like TOTP secrets. After a rotation the previous secret also
    -- signs until previous_secret_expires_at, so receivers can switch over without dropping messages.
    secret                 VARCHAR(200)  NOT NULL,
    previous_secret        VARCHAR(200),
    previous_secret_expires_at TIMESTAMPTZ,
    enabled                BOOLEAN       NOT NULL DEFAULT TRUE,
    -- Why the application turned the endpoint off (410 Gone, too many failures); NULL while enabled or turned off by
    -- its owner.
    disabled_reason        VARCHAR(200),
    consecutive_failures   INTEGER       NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_webhook_endpoints_events CHECK (cardinality(event_types) > 0)
);

CREATE INDEX ix_webhook_endpoints_user_id ON webhook_endpoints (user_id);

CREATE TABLE webhook_deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id     BIGINT       NOT NULL REFERENCES webhook_endpoints (id) ON DELETE CASCADE,
    -- webhook-id header: the same for every attempt, so receivers can drop duplicates.
    message_id      VARCHAR(40)  NOT NULL,
    event_type      VARCHAR(100) NOT NULL,
    -- The exact JSON body that is signed and sent.
    payload         TEXT         NOT NULL,
    status          VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    attempts        INTEGER      NOT NULL DEFAULT 0,
    -- Due time while PENDING; a sender that claims the row moves it forward as a lease, so a crash mid-send only
    -- delays the retry.
    next_attempt_at TIMESTAMPTZ  NOT NULL,
    response_status INTEGER,
    last_error      VARCHAR(500),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at     TIMESTAMPTZ,
    CONSTRAINT ck_webhook_deliveries_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

-- The sender's queue: only pending rows, oldest due first.
CREATE INDEX ix_webhook_deliveries_due ON webhook_deliveries (next_attempt_at) WHERE status = 'PENDING';
-- An endpoint's recent deliveries, newest first (GET /api/v1/webhooks/{id}/deliveries).
CREATE INDEX ix_webhook_deliveries_endpoint ON webhook_deliveries (endpoint_id, id DESC);
-- Retention: finished rows are deleted after app.webhooks.delivery-retention.
CREATE INDEX ix_webhook_deliveries_finished_at ON webhook_deliveries (finished_at) WHERE finished_at IS NOT NULL;
