-- Self-service sign-ups waiting for their email link. The account is created only when the link is opened, so a
-- sign-up with a registered address and one with a new address leave the same trace: no account, no reserved
-- username (no account enumeration). Rows expire with the link and are deleted hourly.
CREATE TABLE pending_registrations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(32)  NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    -- SHA-256 of the token sent by email; the token itself is never stored.
    token_hash    VARCHAR(64)  NOT NULL,
    expires_at    TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_pending_registrations_hash UNIQUE (token_hash)
);

CREATE INDEX ix_pending_registrations_email ON pending_registrations (email);
CREATE INDEX ix_pending_registrations_expires_at ON pending_registrations (expires_at);
