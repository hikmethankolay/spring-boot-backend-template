-- Devices users logged in from, for the new-login alert (KnownDevices). A browser keeps a random device cookie whose
-- SHA-256 is token_hash (OWASP "device cookies"); a client without the cookie is recognized by device (browser family
-- and operating system, e.g. 'Chrome on Windows') and network (IPv4 /24, IPv6 /64). Rows unused for
-- app.mail.security-alerts.new-login-lookback are deleted.

CREATE TABLE known_devices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   VARCHAR(64)   NOT NULL,
    device       VARCHAR(100)  NOT NULL,
    network      VARCHAR(64)   NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL,
    last_seen_at TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_known_devices_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_known_devices_user_id ON known_devices (user_id);
CREATE INDEX ix_known_devices_last_seen_at ON known_devices (last_seen_at);

-- Announcements the owner emailed to many users (BroadcastService), kept as a history.

CREATE TABLE mail_broadcasts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category      VARCHAR(40)   NOT NULL,
    subject       VARCHAR(200)  NOT NULL,
    title         VARCHAR(200)  NOT NULL,
    body          TEXT          NOT NULL,
    -- Comma-separated roles of the audience, e.g. USER,ADMIN.
    roles         VARCHAR(100)  NOT NULL,
    verified_only BOOLEAN       NOT NULL,
    queued        INTEGER       NOT NULL DEFAULT 0,
    suppressed    INTEGER       NOT NULL DEFAULT 0,
    -- True if queuing stopped on an error; the recipients queued before it still get the email.
    partial       BOOLEAN       NOT NULL DEFAULT FALSE,
    created_by    BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ   NOT NULL,
    -- When the recipients were queued (in the background); null while queuing, or if the instance stopped meanwhile.
    finished_at   TIMESTAMPTZ
);

-- Broadcast an email belongs to; null for every other email. The outbox sends emails without one first, in the order
-- of this index, so a large broadcast waiting does not make every scheduled run sort it.
ALTER TABLE email_outbox ADD COLUMN broadcast_id BIGINT REFERENCES mail_broadcasts (id) ON DELETE SET NULL;
CREATE INDEX ix_email_outbox_send_order ON email_outbox ((broadcast_id IS NOT NULL), id);
