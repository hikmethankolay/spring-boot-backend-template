-- Security events, written next to the "audit" log (OWASP Logging; ASVS 5.0 V16, tamper resistance). No foreign key
-- to users: the trail must outlive the accounts it is about.
CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    action      VARCHAR(64)  NOT NULL,
    user_id     BIGINT,
    actor_id    VARCHAR(64),
    client_ip   VARCHAR(64),
    details     JSONB        NOT NULL DEFAULT '{}'
);

CREATE INDEX ix_audit_events_occurred_at ON audit_events (occurred_at);
CREATE INDEX ix_audit_events_user_id ON audit_events (user_id);

-- Append-only: no role but the table owner (the schema owner of the migration Job) may change or remove rows,
-- whatever privileges it was granted, so a compromised app cannot cover its tracks. The owner removes rows only
-- through purge_audit_events below.
CREATE FUNCTION audit_events_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND current_user = (
            SELECT tableowner FROM pg_tables WHERE schemaname = TG_TABLE_SCHEMA AND tablename = TG_TABLE_NAME) THEN
        RETURN NULL;
    END IF;
    RAISE EXCEPTION 'audit_events is append-only (% refused)', TG_OP USING ERRCODE = 'insufficient_privilege';
END
$$;

CREATE TRIGGER audit_events_append_only
    BEFORE UPDATE OR DELETE OR TRUNCATE ON audit_events
    FOR EACH STATEMENT EXECUTE FUNCTION audit_events_append_only();

REVOKE UPDATE, DELETE, TRUNCATE ON audit_events FROM PUBLIC;

-- Retention: removes events older than the given time, as the table owner (SECURITY DEFINER), so the app can run it
-- with its own role. Events younger than 90 days are kept, whoever asks. The search path is fixed to this schema.
CREATE FUNCTION purge_audit_events(older_than TIMESTAMPTZ) RETURNS INTEGER
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = ${flyway:defaultSchema}, pg_temp AS $$
DECLARE
    removed INTEGER;
BEGIN
    IF older_than > now() - INTERVAL '90 days' THEN
        RAISE EXCEPTION 'audit events younger than 90 days are kept (asked to remove those before %)', older_than;
    END IF;
    DELETE FROM audit_events WHERE occurred_at < older_than;
    GET DIAGNOSTICS removed = ROW_COUNT;
    RETURN removed;
END
$$;
